import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// A contiguous writer avoids creating millions of tiny Buffer / vertex objects.
class Writer {
  offset = 0;
  constructor(size) { this.buffer = Buffer.alloc(size); }
  u8(v) { this.buffer.writeUInt8(v, this.offset); this.offset++; }
  i8(v) { this.buffer.writeInt8(v, this.offset); this.offset++; }
  u16(v) { this.buffer.writeUInt16LE(v, this.offset); this.offset += 2; }
  i32(v) { this.buffer.writeInt32LE(v, this.offset); this.offset += 4; }
  f32(v) { assert.ok(Number.isFinite(v)); this.buffer.writeFloatLE(v, this.offset); this.offset += 4; }
  vector(values) { for (const v of values) this.f32(v); }
  text(v) { const b = Buffer.from(v, "utf16le"); this.i32(b.length); b.copy(this.buffer, this.offset); this.offset += b.length; }
}

export async function generateCapacityStage({ columns = 2500, rows = 2000, materials = 16, output } = {}) {
  assert.ok(Number.isInteger(columns) && columns >= 2 && Number.isInteger(rows) && rows >= 2);
  assert.ok(Number.isInteger(materials) && materials >= 1 && materials <= rows);
  const vertexCount = (columns + 1) * (rows + 1), triangleCount = columns * rows * 2;
  const writer = new Writer(vertexCount * 38 + triangleCount * 12 + materials * 512 + 4096);
  for (const v of [0x50, 0x4d, 0x58, 0x20]) writer.u8(v);
  writer.f32(2); writer.u8(8);
  for (const v of [0, 0, 4, 1, 1, 1, 1, 1]) writer.u8(v);
  writer.text(`負荷計測ステージ ${triangleCount} 三角形`);
  writer.text(`Polygon capacity stage ${triangleCount}`);
  writer.text("独自生成の起伏地形。外部画像・モーフ・剛体・ジョイントなし。影の生成と受け取りON、輪郭OFF。");
  writer.text("Generated by scripts/generate-polygon-capacity-stage.mjs; no third-party assets.");
  writer.i32(vertexCount);
  // Same terrain at every density: smooth valleys with steep ridges casting real shadows.
  for (let row = 0; row <= rows; row++) {
    const z = row / rows * 2000 - 1000;
    for (let col = 0; col <= columns; col++) {
      const x = col / columns * 2500 - 1250;
      const a = x / 100, b = z / 120;
      const y = 100 + 85 * Math.sin(a) * Math.cos(b) + 35 * Math.sin(a * 2 + b);
      const dx = 0.85 * Math.cos(a) * Math.cos(b) + 0.7 * Math.cos(a * 2 + b);
      const dz = -85 / 120 * Math.sin(a) * Math.sin(b) + 35 / 120 * Math.cos(a * 2 + b);
      const length = Math.hypot(dx, 1, dz);
      writer.vector([x, y, z]); writer.vector([-dx / length, 1 / length, -dz / length]);
      writer.vector([col / columns, row / rows]);
      writer.u8(0); writer.i8(0); writer.f32(0); // BDEF1, center, no edge.
    }
  }
  writer.i32(triangleCount * 3);
  // Row bands are material groups, keeping the same vertex sharing at all densities.
  for (let row = 0; row < rows; row++) for (let col = 0; col < columns; col++) {
    const a = row * (columns + 1) + col, b = a + columns + 1;
    for (const index of [a, b, a + 1, a + 1, b, b + 1]) writer.i32(index);
  }
  writer.i32(0); writer.i32(materials);
  for (let i = 0; i < materials; i++) {
    const firstRow = Math.floor(i * rows / materials), lastRow = Math.floor((i + 1) * rows / materials);
    writer.text(`地形 ${i + 1}`); writer.text(`Terrain ${i + 1}`);
    writer.vector(i % 2 ? [0.68, 0.72, 0.62, 1] : [0.74, 0.7, 0.6, 1]);
    writer.vector([0, 0, 0]); writer.f32(1); writer.vector([0, 0, 0]);
    writer.u8(0x0e); writer.vector([0, 0, 0, 0]); writer.f32(0);
    writer.i8(-1); writer.i8(-1); writer.u8(0); writer.u8(1); writer.u8(0);
    writer.text("Opaque, casts and receives shadows, no edge or external texture");
    writer.i32((lastRow - firstRow) * columns * 6);
  }
  writer.i32(1); writer.text("センター"); writer.text("Center"); writer.vector([0, 0, 0]);
  writer.i8(-1); writer.i32(0); writer.u16(0x001e); writer.vector([0, 1, 0]);
  writer.i32(0); // morphs
  writer.i32(1); writer.text("Root"); writer.text("Root"); writer.u8(1);
  writer.i32(1); writer.u8(0); writer.i8(0);
  writer.i32(0); writer.i32(0); // rigid bodies, joints
  const bytes = writer.buffer.subarray(0, writer.offset);
  const report = { columns, rows, triangleCount, vertexCount, materials, bytes: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
    bounds: { x: [-1250, 1250], y: [-20, 220], z: [-1000, 1000] },
    bones: 1, morphs: 0, rigidBodies: 0, joints: 0, externalTextures: 0 };
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, bytes);
  await writeFile(`${output}.json`, JSON.stringify(report, null, 2));
  return report;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const columns = Number(process.argv[2] ?? 2500), rows = Number(process.argv[3] ?? 2000);
  const output = resolve(root, "local-references/polygon-capacity", `stage-${columns * rows * 2}.pmx`);
  console.log(JSON.stringify({ output, ...await generateCapacityStage({ columns, rows, output }) }));
}
