/** One geometry source for PMX and text .x; the opening has no polygons. */
export function createRcWindowRoom(shutter = false) {
  const vertices = [], materials = [];
  const material = (name, diffuse) => {
    const result = { name, diffuse, indices: [] }; materials.push(result); return result;
  };
  const quad = (group, points, normal) => {
    const first = vertices.length;
    points.forEach((position, index) => vertices.push({ position, normal, uv: [[0, 0], [0, 1], [1, 1], [1, 0]][index] }));
    group.indices.push(first, first + 1, first + 2, first, first + 2, first + 3);
  };
  const windowWall = (group, left, right, bottom, top) => quad(group,
    [[left, bottom, 6], [left, top, 6], [right, top, 6], [right, bottom, 6]], [0, 0, -1]);
  if (shutter) {
    // Black suppresses secondary reflection from the shutter itself.
    windowWall(material("WindowShutter", [0, 0, 0]), -2, 2, 1.2, 4.8);
  } else {
    const white = material("RoomWhite", [0.8, 0.8, 0.8]);
    const red = material("RedFloorSource", [0.9, 0.025, 0.025]);
    const floor = (group, left, right, near, far) => quad(group,
      [[left, 0, near], [left, 0, far], [right, 0, far], [right, 0, near]], [0, 1, 0]);
    // Five adjacent panels tile the entire floor, with no coplanar overlap.
    floor(white, -6, -1.5, -6, 6); floor(white, 1.5, 6, -6, 6);
    floor(white, -1.5, 1.5, -6, 1.5); floor(white, -1.5, 1.5, 3.5, 6);
    floor(red, -1.5, 1.5, 1.5, 3.5);
    quad(white, [[-6, 6, -6], [6, 6, -6], [6, 6, 6], [-6, 6, 6]], [0, -1, 0]);
    quad(white, [[-6, 0, -6], [6, 0, -6], [6, 6, -6], [-6, 6, -6]], [0, 0, 1]);
    quad(white, [[-6, 0, -6], [-6, 6, -6], [-6, 6, 6], [-6, 0, 6]], [1, 0, 0]);
    quad(white, [[6, 0, -6], [6, 0, 6], [6, 6, 6], [6, 6, -6]], [-1, 0, 0]);
    windowWall(white, -6, -2, 0, 6); windowWall(white, 2, 6, 0, 6);
    windowWall(white, -2, 2, 0, 1.2); windowWall(white, -2, 2, 4.8, 6);
  }
  return { name: shutter ? "WindowShutter" : "WindowRoom", vertices, materials };
}

class PmxWriter {
  chunks = [];
  number(method, bytes, value) { const buffer = Buffer.alloc(bytes); buffer[method](value); this.chunks.push(buffer); }
  u8(value) { this.number("writeUInt8", 1, value); }
  i8(value) { this.number("writeInt8", 1, value); }
  u16(value) { this.number("writeUInt16LE", 2, value); }
  i32(value) { this.number("writeInt32LE", 4, value); }
  f32(value) { this.number("writeFloatLE", 4, value); }
  vector(values) { values.forEach(value => this.f32(value)); }
  text(value) { const buffer = Buffer.from(value, "utf16le"); this.i32(buffer.length); this.chunks.push(buffer); }
}

export function encodeRcWindowRoomPmx(model) {
  assert.ok(model.vertices.length < 256);
  const w = new PmxWriter();
  [0x50, 0x4d, 0x58, 0x20].forEach(value => w.u8(value)); w.f32(2); w.u8(8);
  [0, 0, 1, 1, 1, 1, 1, 1].forEach(value => w.u8(value));
  w.text(model.name); w.text(model.name);
  w.text("MMD_modoki original window-room fixture. MIT. No external assets; real geometry opening.");
  w.text("Generated by scripts/generate-rc-window-room-fixture.mjs");
  w.i32(model.vertices.length);
  for (const vertex of model.vertices) {
    w.vector(vertex.position); w.vector(vertex.normal); w.vector(vertex.uv); w.u8(0); w.i8(0); w.f32(0);
  }
  const indices = model.materials.flatMap(material => material.indices);
  w.i32(indices.length); indices.forEach(index => w.u8(index));
  w.i32(0); w.i32(model.materials.length);
  for (const material of model.materials) {
    w.text(material.name); w.text(material.name); w.vector([...material.diffuse, 1]);
    w.vector([0, 0, 0]); w.f32(0); w.vector([0, 0, 0]);
    w.u8(1); // Double-sided only: no edge or shadow-map flags.
    w.vector([0, 0, 0, 0]); w.f32(0);
    w.i8(-1); w.i8(-1); w.u8(0); w.u8(0); w.i8(-1); // No texture, sphere or toon.
    w.text("Original matte opaque material"); w.i32(material.indices.length);
  }
  w.i32(1); w.text("センター"); w.text("Center"); w.vector([0, 0, 0]);
  w.i8(-1); w.i32(0); w.u16(0x001e); w.vector([0, 1, 0]);
  w.i32(0); // No morphs.
  w.i32(1); w.text("Root"); w.text("Root"); w.u8(1); w.i32(1); w.u8(0); w.i8(0);
  w.i32(0); w.i32(0); // No rigid bodies or joints.
  return Buffer.concat(w.chunks);
}

const sequence = (values, format, indent = "  ") => values.map((value, index) =>
  `${indent}${format(value)}${index === values.length - 1 ? ";" : ","}`).join("\n");

export function encodeRcWindowRoomX(model, texture = null) {
  const triangles = model.materials.flatMap((material, materialIndex) => {
    const faces = [];
    for (let i = 0; i < material.indices.length; i += 3) faces.push({ indices: material.indices.slice(i, i + 3), materialIndex });
    return faces;
  });
  const faces = sequence(triangles, face => `3;${face.indices.join(",")};`);
  return `xof 0303txt 0032

// Original MMD_modoki fixture, MIT. The window is a geometry opening.
Mesh ${model.name} {
  ${model.vertices.length};
${sequence(model.vertices, vertex => `${vertex.position.join(";")};`)}
  ${triangles.length};
${faces}
  MeshNormals {
    ${model.vertices.length};
${sequence(model.vertices, vertex => `${vertex.normal.join(";")};`, "    ")}
    ${triangles.length};
${faces}
  }
  MeshTextureCoords {
    ${model.vertices.length};
${sequence(model.vertices, vertex => `${vertex.uv[0]};${1 - vertex.uv[1]};`, "    ")}
  }
  MeshMaterialList {
    ${model.materials.length};
    ${triangles.length};
${sequence(triangles, face => String(face.materialIndex), "    ")}
${model.materials.map(material => `    Material ${material.name} {
      ${material.diffuse.join(";")};1;;
      0;
      0;0;0;;
      0;0;0;;${texture ? `
      TextureFilename { "${texture}"; }` : ""}
    }`).join("\n")}
  }
}
`;
}

function geometryRows(model) {
  return model.materials.flatMap(material => material.indices.map(index => ({
    material: material.name, position: model.vertices[index].position.map(Math.fround),
    normal: model.vertices[index].normal, uv: model.vertices[index].uv,
  })));
}

async function validateFixtures(files, models) {
  // Expose the real parser only inside this static SSR process; do not change runtime source.
  const vite = await createServer({ root, configFile: false, appType: "custom", logLevel: "silent",
    ssr: { noExternal: ["babylon-mmd", /^@babylonjs\//] },
    server: { middlewareMode: true }, plugins: [{ name: "fixture-static-x-parser", enforce: "pre",
      transform(code, id) {
        if (id.replace(/\\/g, "/").endsWith("/src/x-file-loader.ts")) {
          return `${code}\nexport { parseX as parseFixtureX, buildTriangulatedMeshData as triangulateFixtureX };`;
        }
      } }] });
  try {
    const { PmxReader } = await vite.ssrLoadModule("/node_modules/babylon-mmd/esm/Loader/Parser/pmxReader.js");
    const { parseFixtureX, triangulateFixtureX } = await vite.ssrLoadModule("/src/x-file-loader.ts");
    for (const [file, model] of files) {
      const bytes = await readFile(resolve(directory, file));
      const expected = geometryRows(model);
      if (file.endsWith(".pmx")) {
        const pmx = await PmxReader.ParseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
        const actual = []; let offset = 0;
        for (const material of pmx.materials) {
          assert.equal(material.flag, 1); assert.equal(material.diffuse[3], 1);
          assert.equal(material.shininess, 0); assert.deepEqual(material.specular, [0, 0, 0]);
          assert.deepEqual(material.ambient, [0, 0, 0]); assert.equal(material.toonTextureIndex, -1);
          assert.deepEqual(material.diffuse.slice(0, 3), model.materials.find(value => value.name === material.name).diffuse.map(Math.fround));
          for (let i = 0; i < material.indexCount; i++) {
            const vertex = pmx.vertices[pmx.indices[offset++]];
            actual.push({ material: material.name, position: vertex.position, normal: vertex.normal, uv: vertex.uv });
          }
        }
        assert.equal(pmx.textures.length, 0); assert.equal(pmx.morphs.length, 0); assert.equal(pmx.rigidBodies.length, 0);
        assert.deepEqual(actual, expected, file);
      } else {
        const parsed = parseFixtureX(bytes.toString("utf8")); assert.equal(parsed.root.meshes.length, 1);
        const mesh = parsed.root.meshes[0], geometry = triangulateFixtureX(mesh);
        assert.equal(geometry.redundantFaceCount, 0);
        const actual = geometry.indices.map((index, corner) => {
          const material = mesh.mats[mesh.faceMats[geometry.faceId[Math.floor(corner / 3)]]];
          return { material: material.name, position: geometry.positions.slice(index * 3, index * 3 + 3).map(Math.fround),
            normal: geometry.normals.slice(index * 3, index * 3 + 3), uv: geometry.uvs.slice(index * 2, index * 2 + 2) };
        });
        assert.deepEqual(actual, expected, file);
        for (const [i, material] of mesh.mats.entries()) {
          assert.deepEqual(material.diffuse.asArray(), [...model.materials[i].diffuse, 1]);
          assert.equal(material.power, 0); assert.deepEqual(material.specular.asArray(), [0, 0, 0]);
          assert.deepEqual(material.emissive.asArray(), [0, 0, 0]);
          assert.equal(material.texture, file.includes("opaque-png") ? "white.png" : file.includes("opaque-jpg") ? "white.jpg" : null);
        }
      }
    }
    for (const model of models) {
      assert.ok(geometryRows(model).length / 3 <= 120);
      for (const material of model.materials) for (let i = 0; i < material.indices.length; i += 3) {
        const [a, b, c] = material.indices.slice(i, i + 3).map(index => model.vertices[index]);
        const u = b.position.map((v, j) => v - a.position[j]), v = c.position.map((v, j) => v - a.position[j]);
        const cross = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
        assert.ok(cross.reduce((sum, value, j) => sum + value * a.normal[j], 0) > 0, "Nondegenerate winding matches explicit normal");
      }
    }
  } finally { await vite.close(); }
}

export async function generateRcWindowRoomFixture() {
  await mkdir(directory, { recursive: true });
  const room = createRcWindowRoom(), shutter = createRcWindowRoom(true), files = [];
  for (const [file, model, texture] of [
    ["window-room.pmx", room], ["window-room-plain.x", room],
    ["window-room-opaque-png.x", room, "white.png"], ["window-room-opaque-jpg.x", room, "white.jpg"],
    ["window-shutter.pmx", shutter], ["window-shutter.x", shutter],
  ]) {
    await writeFile(resolve(directory, file), file.endsWith(".pmx") ? encodeRcWindowRoomPmx(model) : encodeRcWindowRoomX(model, texture));
    files.push([file, model]);
  }
  const white = { width: 8, height: 8, data: Buffer.alloc(8 * 8 * 4, 255) };
  const png = PNG.sync.write(white, { colorType: 6 }), jpg = jpegjs.encode(white, 100).data;
  for (const [name, bytes, decoded] of [["white.png", png, PNG.sync.read(png)], ["white.jpg", jpg, jpegjs.decode(jpg)]]) {
    assert.equal(decoded.width, 8); assert.equal(decoded.height, 8);
    assert.ok(decoded.data.every(value => value === 255), `${name} must decode to opaque white`);
    await writeFile(resolve(directory, name), bytes);
  }
  await validateFixtures(files, [room, shutter]);
  return { directory, files: [...files.map(([file]) => file), "white.png", "white.jpg"], roomTriangles: 26,
    shutterTriangles: 2, staticParseAndMatchingGeometry: "passed", textureDecode: "opaque white 8x8 passed" };
}

